-- ─────────────────────────────────────────────────────────────────
-- 010: excluded_payment_tiyin в fiscal_receipts
-- ─────────────────────────────────────────────────────────────────
--
-- Зачем: магазин в Узбекистане часто принимает оплату через Click/Payme
-- (электронные платёжные системы), которые НЕ фискализируются через ОФД.
-- Пример: клиент купил на 300 000 сум, заплатил 150 000 наличными
-- + 150 000 через Click → магазин выдаёт фискальный чек только на
-- 150 000 (наличные), Click учитывается отдельно.
--
-- Перед фискализацией кассир в Receipt.tsx вводит «Сумма через Click/Payme»
-- — эта сумма исключается из эффективной таргет-суммы matcher'а и из
-- безналичной части ReceivedCard. Сохраняем её в БД для аудита и
-- возможных отчётов «сколько было Click/Payme за день/месяц».
--
-- В ОФД не отправляется (это сумма ВНЕ фискального чека).
--
-- Значения:
--   0 → обычная фискализация (default для всех старых чеков)
--   >0 → магазин вычел эту сумму как Click/Payme; фискальный чек =
--        ms_sum - excluded_payment_tiyin

ALTER TABLE fiscal_receipts
  ADD COLUMN excluded_payment_tiyin INTEGER NOT NULL DEFAULT 0;
