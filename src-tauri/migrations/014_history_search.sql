-- Быстрый поиск в Истории чеков (товар / № чека / фискальный признак / даты).
--
-- 1. `search_text` — денормализованная строка поиска: имена товаров + ИКПУ +
--    № чека МС и ФМ + фискальный признак + терминал. Ищем по ней, а НЕ по
--    `request_json`: там 5–50 КБ JSON на чек, и LIKE по блобу читает всю
--    таблицу целиком (десятки МБ на каждый ввод символа).
--
--    ⚠️ Значение пишем СРАЗУ в нижнем регистре (нормализация в JS). Причина:
--    SQLite LIKE регистронезависим только для ASCII — кириллица нет. Без
--    предварительного lower() запрос «коронка» не нашёл бы «Коронка», а
--    SQL-функция lower() кириллицу тоже не приводит.
--
-- 2. Индекс на `fiscalized_at` — его не было вообще: и ORDER BY (пагинация
--    Истории), и будущий фильтр по датам делали полный скан + сортировку.
--
-- 3. Частичный индекс для backfill: после разовой дозаливки он пустой, и
--    проверка «есть ли необработанные чеки» становится мгновенной вместо
--    скана всей таблицы при каждом открытии Истории.

ALTER TABLE fiscal_receipts ADD COLUMN search_text TEXT;

CREATE INDEX IF NOT EXISTS idx_fiscal_receipts_fiscalized
  ON fiscal_receipts(fiscalized_at DESC);

CREATE INDEX IF NOT EXISTS idx_fiscal_receipts_search_pending
  ON fiscal_receipts(id) WHERE search_text IS NULL;
