-- Migration 004: удалить legacy esf_items с source != 'remote'.
--
-- В версиях ≤ 0.9 программа умела импортировать Excel прямо в локальную DB
-- (esf_items с source='excel' / 'didox' / 'e-faktura'). С 0.10+ источник
-- истины — общий пул на mytoolbox-сервере, синкается с source='remote'.
--
-- В 0.10.4 матчер начал фильтровать source='remote', но физически старые
-- записи остались в DB и могли:
--   - засорять Справочник (Catalog UI его не фильтровал)
--   - в редких case'ах попадать в фискализацию если фильтр не отработает
--   - создавать иллюзию «больше товаров чем есть»
--
-- Удаляем только записи которые **никогда не использовались** в реальных
-- фискальных чеках (qty_consumed = 0). Использованные — оставляем для
-- сохранения аудит-следа: replacement_log/match_items могут на них ссылаться.
--
-- Идемпотентно: повторный запуск ничего не сделает (записей source != 'remote'
-- уже не будет).

DELETE FROM esf_items
WHERE source != 'remote'
  AND qty_consumed = 0;
