-- ─────────────────────────────────────────────────────────────────
-- 009: card_kind в fiscal_receipts — тип карты для печати на ленте
-- ─────────────────────────────────────────────────────────────────
--
-- Зачем: кассир перед фискализацией в Receipt.tsx выбирает тип карты
-- (Jismoniy shaxs / Korporativ) для смешанных и карточных оплат. Этот
-- выбор печатается строкой «Karta turi» на бумажном чеке. Чтобы при
-- повторной печати из Истории или при печати refund-чека этот тип
-- сохранялся — храним его в БД рядом с фискальным чеком.
--
-- В ОФД не отправляется (JSON-RPC Api.SendSaleReceipt не принимает поле,
-- см. docs/external-apis/epos-mobile-api.md). Это локальная атрибутика
-- чека для бумажной ленты, как делает E-POS Cashdesk.
--
-- Значения:
--   NULL  → строка «Karta turi» не печатается (legacy чеки до 0.10.30,
--           или оплата чисто наличкой)
--   'fiz' → «Karta turi: Jismoniy shaxs»
--   'corp'→ «Karta turi: Korporativ»

ALTER TABLE fiscal_receipts ADD COLUMN card_kind TEXT;
